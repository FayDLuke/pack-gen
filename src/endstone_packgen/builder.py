from __future__ import annotations

import hashlib
import json
import shutil
import tomllib
import uuid
import zipfile
from dataclasses import dataclass
from pathlib import Path

NAMESPACE = uuid.UUID("6f1c2a52-8d0b-4b8e-9f5e-3a6f0c1d7e41")

RESOURCES = "resources"
DATA = "data"

# Directories that only exist in one pack type. "animations" and
# "animation_controllers" are left out because both types use them.
RESOURCE_MARKERS = {"textures", "texts", "ui", "sounds", "models", "attachables", "particles",
                    "render_controllers", "materials", "fonts", "entity"}
DATA_MARKERS = {"scripts", "entities", "items", "blocks", "functions", "loot_tables", "recipes",
                "spawn_rules", "trading", "structures", "dialogue", "features", "feature_rules"}

IGNORED_NAMES = {".DS_Store", "Thumbs.db", "pack.toml", "__pycache__"}

# Fixed so identical content always produces a byte-identical archive.
ZIP_EPOCH = (2020, 1, 1, 0, 0, 0)


class PackError(Exception):
    pass


@dataclass
class PackSpec:
    name: str
    source: Path
    kind: str
    description: str
    base_version: list[int]
    min_engine: list[int]
    custom_manifest: dict | None


def iter_files(source: Path) -> list[Path]:
    files = []
    for path in sorted(source.rglob("*")):
        rel = path.relative_to(source)
        if not path.is_file() or any(p in IGNORED_NAMES or p.startswith(".") for p in rel.parts):
            continue
        files.append(rel)
    return files


def content_hash(source: Path) -> str:
    digest = hashlib.sha256()
    for rel in iter_files(source):
        digest.update(rel.as_posix().encode())
        digest.update(b"\0")
        digest.update((source / rel).read_bytes())
        digest.update(b"\0")
    config = source / "pack.toml"
    if config.is_file():
        digest.update(config.read_bytes())
    return digest.hexdigest()


def detect_kind(source: Path) -> str:
    top = {p.name for p in source.iterdir() if p.is_dir()}
    has_resources = bool(top & RESOURCE_MARKERS) or (source / "blocks.json").is_file()
    has_data = bool(top & DATA_MARKERS)
    if has_resources and has_data:
        raise PackError("contains both resource and behavior content; split it into two folders or set type in pack.toml")
    if not (has_resources or has_data):
        raise PackError("no recognizable pack content; add folders like textures/ or scripts/, or set type in pack.toml")
    return RESOURCES if has_resources else DATA


def _kind_from_manifest(manifest: dict) -> str:
    types = {m.get("type") for m in manifest.get("modules", [])}
    if types & {DATA, "script"}:
        return DATA
    if RESOURCES in types:
        return RESOURCES
    raise PackError("manifest.json has no resources/data/script module")


def load_spec(source: Path) -> PackSpec:
    config = {}
    config_path = source / "pack.toml"
    if config_path.is_file():
        try:
            config = tomllib.loads(config_path.read_text(encoding="utf-8"))
        except tomllib.TOMLDecodeError as exc:
            raise PackError(f"invalid pack.toml: {exc}") from exc

    manifest = None
    manifest_path = source / "manifest.json"
    if manifest_path.is_file():
        try:
            manifest = json.loads(manifest_path.read_text(encoding="utf-8-sig"))
            manifest["header"]["uuid"], manifest["header"]["version"]
        except (json.JSONDecodeError, KeyError, TypeError) as exc:
            raise PackError(f"invalid manifest.json: {exc}") from exc

    kind = config.get("type")
    if kind is None:
        kind = _kind_from_manifest(manifest) if manifest else detect_kind(source)
    elif kind not in (RESOURCES, DATA):
        raise PackError(f"type must be '{RESOURCES}' or '{DATA}', got '{kind}'")

    name = config.get("name", source.name)
    return PackSpec(
        name=name,
        source=source,
        kind=kind,
        description=config.get("description", f"{name} (generated by PackGen)"),
        base_version=list(config.get("version", [1, 0, 0])),
        min_engine=list(config.get("min_engine_version", [1, 21, 0])),
        custom_manifest=manifest,
    )


def build_manifest(spec: PackSpec, version: list[int]) -> dict:
    return {
        "format_version": 2,
        "header": {
            "name": spec.name,
            "description": spec.description,
            "uuid": str(uuid.uuid5(NAMESPACE, f"{spec.name}:header")),
            "version": version,
            "min_engine_version": spec.min_engine,
        },
        "modules": [
            {
                "type": spec.kind,
                "uuid": str(uuid.uuid5(NAMESPACE, f"{spec.name}:module")),
                "version": version,
            }
        ],
    }


def next_version(base: list[int], previous: dict | None, digest: str) -> tuple[list[int], int]:
    """Bump the patch number when content changes; clients cache packs by uuid and version."""
    if previous is None:
        build = 0
    elif previous["hash"] == digest:
        build = previous["build"]
    else:
        build = previous["build"] + 1
    major, minor, patch = (base + [0, 0, 0])[:3]
    return [major, minor, patch + build], build


def write_archive(source: Path, manifest: dict | None, dest: Path) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    tmp = dest.with_name(dest.name + ".tmp")
    with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as archive:
        entries = {rel.as_posix(): (source / rel).read_bytes() for rel in iter_files(source)}
        if manifest is not None:
            entries["manifest.json"] = json.dumps(manifest, indent=2).encode()
        for arcname in sorted(entries):
            info = zipfile.ZipInfo(arcname, ZIP_EPOCH)
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, entries[arcname])
    tmp.replace(dest)


def write_folder(source: Path, manifest: dict | None, dest: Path) -> None:
    if dest.exists():
        shutil.rmtree(dest)
    for rel in iter_files(source):
        target = dest / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source / rel, target)
    if manifest is not None:
        (dest / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")


def set_world_pack(json_path: Path, pack_id: str, version: list[int] | None) -> None:
    """Add or update a pack entry in a world_*_packs.json file; version None removes it."""
    entries = []
    if json_path.is_file():
        try:
            entries = json.loads(json_path.read_text(encoding="utf-8-sig"))
        except json.JSONDecodeError as exc:
            raise PackError(f"{json_path.name} is not valid JSON: {exc}") from exc
    entries = [e for e in entries if e.get("pack_id") != pack_id]
    if version is not None:
        entries.append({"pack_id": pack_id, "version": version})
    if entries or json_path.is_file():
        json_path.parent.mkdir(parents=True, exist_ok=True)
        json_path.write_text(json.dumps(entries, indent=2), encoding="utf-8")
